  'Every day in the United States, 17 people die waiting for an organ transplant. That number is staggering — and largely preventable. Living donation offers a powerful alternative to waiting for a deceased donor: a healthy person voluntarily donates part of an organ — a kidney, a portion of their liver, or bone marrow — to someone in need.

## What Is Living Donation?

Living donation occurs when a living person donates an organ or part of an organ to a recipient. The most common forms of living donation include:

- **Kidney donation**: The most common form of living organ donation. Humans have two kidneys and can live a completely normal life with just one.
- **Liver donation**: A portion of the liver is donated. Both the donor''s and recipient''s liver segments regenerate to full size within weeks.
- **Bone marrow/stem cell donation**: Donors contribute stem cells that help rebuild a patient''s blood and immune system.

## The Impact of One Decision

When someone chooses to become a living donor, the ripple effects are extraordinary. Not only does the recipient gain potentially decades of additional life, but the act of donation often inspires others in their community to consider donation themselves.

Studies show that patients who receive living donor organs experience better outcomes than those who receive organs from deceased donors. Transplants can be scheduled at an optimal time for both donor and recipient, rather than happening urgently in the middle of the night.

## How Save One Person Helps

Save One Person was founded on a simple belief: if people knew that someone needed them, many would step forward to help. The challenge is visibility. Patients and potential donors share the same world but rarely cross paths.

